#!/usr/bin/env bash
# Query upstream sources for the apps in gitlist.txt and (re)generate their
# PKGBUILD files in builds/ (existing PKGBUILDs are overwritten).
#
# gitlist.txt format, one app per line:
#   <name> <github-owner/repo> [overrides]
#
# Overrides (semicolon-separated, no spaces):
#   type=release|go|npm   where the version/source comes from (default: release)
#   depends=a,b,c         extra runtime dependencies for the PKGBUILD
#   asset=<filename>      (release) exact release asset to use
#   npm=<package>         (npm) npm package name (default: <name>)
#   scripts=a,b           (npm) packages whose install scripts are allowed
#   license=<SPDX>        license id override (go/npm only)
#
# Usage:
#   ./gitfind.sh                 # process every app in gitlist.txt
#   ./gitfind.sh photocraft ...  # process only the named apps
#
# GITHUB_TOKEN is honored if set (raises the GitHub API rate limit).

set -uo pipefail

BUILD_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PKGBUILD_DIR="$BUILD_ROOT/builds"
APPS_CONF="$BUILD_ROOT/gitlist.txt"
ARCH_ASSET="linux-x86_64"
GITHUB_API="https://api.github.com"
NPM_REGISTRY="https://registry.npmjs.org"

SELECTED=()

while (($#)); do
  case $1 in
  -h|--help)
    sed -n '1,21p' "$0"
    exit 0
    ;;
  -*)
    echo "unknown option: $1" >&2
    exit 1
    ;;
  *)
    SELECTED+=("$1")
    ;;
  esac
  shift
done

for tool in curl jq sha256sum sort; do
  command -v "$tool" >/dev/null || { echo "missing dependency: $tool" >&2; exit 1; }
done
[[ -f $APPS_CONF ]] || { echo "no gitlist.txt at $APPS_CONF" >&2; exit 1; }
mkdir -p "$PKGBUILD_DIR"

log() { printf '%s\n' "$*"; }

gh() { # GET a GitHub API url
  if [[ -n ${GITHUB_TOKEN:-} ]]; then
    curl --compressed -fsSL \
      -H "Authorization: Bearer $GITHUB_TOKEN" \
      -H "X-GitHub-Api-Version: 2022-11-28" "$@"
  else
    curl --compressed -fsSL "$@"
  fi
}

strip_version() { # $1=tag $2=pkgname -> plain version
  local v=$1
  v=${v#"$2"-}
  v=${v#[vV]}
  printf '%s' "$v"
}

clean_desc() { # strip chars that would break a PKGBUILD string, collapse newlines
  local d=$1
  d=${d//\"/}
  d=${d//\`/}
  d=${d//\$/}
  d=${d//$'\n'/ }
  printf '%s' "$d"
}

depends_expr() { # $1=comma list -> "( 'a' 'b' )" (empty -> "()")
  local csv=$1 d items=()
  if [[ -n $csv ]]; then
    local dlist=()
    IFS=',' read -ra dlist <<<"$csv"
    for d in "${dlist[@]}"; do
      [[ -n $d ]] && items+=("'$d'")
    done
  fi
  printf '(%s)' "${items[*]}"
}

desc_for() { # $1=repo -> repo description (best effort)
  local d=""
  d=$(gh "$GITHUB_API/repos/$1" 2>/dev/null | jq -r '.description // empty' 2>/dev/null) || d=""
  printf '%s' "$d"
}

license_for() { # $1=repo -> SPDX id from the GitHub license endpoint (best effort)
  local spdx=""
  spdx=$(gh "$GITHUB_API/repos/$1/license" 2>/dev/null | jq -r '.license.spdx_id // empty' 2>/dev/null) || spdx=""
  printf '%s' "$spdx"
}

# ---------------------------------------------------------------- generators ---

write_release_pkgbuild() { # $1=name $2=repo $3=ver $4=tag $5=asset $6=url $7=sha $8=desc $9=depends_csv
  local name=$1 repo=$2 ver=$3 tag=$4 asset=$5 url=$6 sha=$7 desc=$8 depends_csv=$9
  local depends
  depends=$(depends_expr "$depends_csv")

  cat >"$PKGBUILD_DIR/${name}_PKGBUILD" <<PKEOF
# Maintainer: generated by gitfind.sh (in the same directory) — do not edit by hand
# upstream release: $tag
pkgname=$name
pkgver=$ver
pkgrel=1
pkgdesc="$desc"
arch=('x86_64')
url="https://github.com/$repo"
license=('Apache-2.0' 'MIT')
depends=$depends
options=('!strip' '!debug')
source=("$asset::$url")
sha256sums=('$sha')

build() {
  :
}

package() {
  local top
  top=\$(find "\$srcdir" -mindepth 1 -maxdepth 1 -type d | head -n1)
  cd "\$top" || return 1

  local f
  for f in bin/*; do
    install -Dm755 "\$f" "\$pkgdir/usr/bin/\$(basename "\$f")"
  done

  install -d "\$pkgdir/usr/share"
  cp -a share/. "\$pkgdir/usr/share/"

  if ls share/doc/\$pkgname/LICENSE-* >/dev/null 2>&1; then
    install -d "\$pkgdir/usr/share/licenses/\$pkgname"
    cp -a share/doc/\$pkgname/LICENSE-* "\$pkgdir/usr/share/licenses/\$pkgname/"
  fi
}
PKEOF
}

write_go_pkgbuild() { # $1=name $2=repo $3=ver $4=tag $5=desc $6=license $7=depends_csv
  local name=$1 repo=$2 ver=$3 tag=$4 desc=$5 license=$6 depends_csv=$7
  local depends
  depends=$(depends_expr "$depends_csv")

  cat >"$PKGBUILD_DIR/${name}_PKGBUILD" <<PKEOF
# Maintainer: generated by gitfind.sh (in the same directory) — do not edit by hand
# upstream tag: $tag
pkgname=$name
pkgver=$ver
pkgrel=1
pkgdesc="$desc"
arch=('x86_64')
url="https://github.com/$repo"
license=('$license')
depends=$depends
makedepends=('go')
options=('!strip' '!debug')
source=("$name-$ver.tar.gz::https://github.com/$repo/archive/refs/tags/$tag.tar.gz")
# GitHub tag-archive checksums are not guaranteed stable.
sha256sums=('SKIP')

build() {
  local top
  top=\$(find "\$srcdir" -mindepth 1 -maxdepth 1 -type d | head -n1)
  cd "\$top" || return 1
  export CGO_ENABLED=0
  go build -trimpath -ldflags '-s -w' -o "$name" .
}

package() {
  local top
  top=\$(find "\$srcdir" -mindepth 1 -maxdepth 1 -type d | head -n1)
  cd "\$top" || return 1
  install -Dm755 "$name" "\$pkgdir/usr/bin/$name"
  if [[ -f LICENSE ]]; then
    install -Dm644 LICENSE "\$pkgdir/usr/share/licenses/$name/LICENSE"
  fi
}
PKEOF
}

write_npm_pkgbuild() { # $1=name $2=repo $3=ver $4=tarball $5=sha $6=desc $7=license $8=scripts_csv $9=depends_csv
  local name=$1 repo=$2 ver=$3 tarball=$4 sha=$5 desc=$6 license=$7 scripts_csv=$8 depends_csv=$9
  local dep_all="nodejs" depends npm_cmd
  [[ -n $depends_csv ]] && dep_all="nodejs,$depends_csv"
  depends=$(depends_expr "$dep_all")
  npm_cmd="npm install -g --prefix \"\$pkgdir/usr\" --no-fund --no-audit \"\$srcdir/$name-$ver.tgz\""
  # Only allow-list install scripts when the caller asks (native deps like keytar).
  [[ -n $scripts_csv ]] && npm_cmd="npm_config_allow_scripts=$scripts_csv $npm_cmd"

  cat >"$PKGBUILD_DIR/${name}_PKGBUILD" <<PKEOF
# Maintainer: generated by gitfind.sh (in the same directory) — do not edit by hand
# upstream npm: $name@$ver
pkgname=$name
pkgver=$ver
pkgrel=1
pkgdesc="$desc"
arch=('any')
url="https://github.com/$repo"
license=('$license')
depends=$depends
makedepends=('npm')
options=('!strip' '!debug')
source=("$name-$ver.tgz::$tarball")
sha256sums=('$sha')

build() {
  :
}

package() {
  cd "\$srcdir"
  $npm_cmd
  if [[ -f package/LICENSE ]]; then
    install -Dm644 package/LICENSE "\$pkgdir/usr/share/licenses/$name/LICENSE"
  fi
}
PKEOF
}

# ------------------------------------------------------------------ updaters ---

declare -a R_OK R_SKIP R_FAIL
FAILED=0

process_release() { # $1=name $2=repo $3=asset_ov $4=depends_csv
  local name=$1 repo=$2 asset_ov=$3 depends_csv=$4
  local builddir="$PKGBUILD_DIR/.build-$name"

  local rel tag
  if ! rel=$(gh "$GITHUB_API/repos/$repo/releases/latest"); then
    log "  ERROR: could not fetch latest release (no releases, rate limited, or repo missing)"
    R_FAIL+=("$name"); FAILED=1; return 0
  fi
  tag=$(jq -r '.tag_name // empty' <<<"$rel")
  if [[ -z $tag ]]; then
    log "  ERROR: latest release has no tag"
    R_FAIL+=("$name"); FAILED=1; return 0
  fi
  local ver
  ver=$(strip_version "$tag" "$name")
  log "  latest: $tag (version $ver)"

  local asset sha url
  if [[ -n $asset_ov ]]; then
    asset=$asset_ov
    url=$(jq -r --arg a "$asset" '.assets[] | select(.name == $a) | .browser_download_url // empty' <<<"$rel" | head -n1)
  else
    url=$(jq -r --arg p "${name}-${ver}-${ARCH_ASSET}.tar.gz" \
      '.assets[] | select(.name == $p) | .browser_download_url' <<<"$rel" | head -n1)
    if [[ -z $url ]]; then # fall back to any main (non -cli-) linux x86_64 tarball
      url=$(jq -r --arg pre "${name}-" \
        '.assets[] | select(.name | startswith($pre))
                     | select(.name | endswith("-'"$ARCH_ASSET"'.tar.gz"))
                     | select(.name | contains("-cli-") | not)
                     | .browser_download_url' <<<"$rel" | head -n1)
    fi
    asset=${url##*/}
  fi
  if [[ -z $url || -z $asset ]]; then
    log "  SKIP: no ${ARCH_ASSET} tarball in release $tag"
    R_SKIP+=("$name (no asset)"); return 0
  fi
  log "  asset: $asset"

  sha=$(jq -r --arg a "$asset" \
    '.assets[] | select(.name == $a) | .digest // "" | sub("^sha256:"; "")' <<<"$rel")
  if [[ ! $sha =~ ^[0-9a-f]{64}$ ]]; then
    log "  no sha256 digest in API response, downloading to compute checksum..."
    mkdir -p "$builddir"
    if ! curl --compressed -fsSL -o "$builddir/$asset" "$url"; then
      log "  ERROR: download failed"
      rm -rf "$builddir"
      R_FAIL+=("$name"); FAILED=1; return 0
    fi
    sha=$(sha256sum "$builddir/$asset" | awk '{print $1}')
    rm -rf "$builddir"
  fi

  local desc
  desc=$(clean_desc "$(desc_for "$repo")")
  [[ -n $desc ]] || desc="$name"

  write_release_pkgbuild "$name" "$repo" "$ver" "$tag" "$asset" "$url" "$sha" "$desc" "$depends_csv"
  log "  builds/${name}_PKGBUILD updated (pkgver=$ver)"
  R_OK+=("$name -> $ver")
}

process_go() { # $1=name $2=repo $3=depends_csv $4=license_ov
  local name=$1 repo=$2 depends_csv=$3 license_ov=$4

  local tags tag
  if ! tags=$(gh "$GITHUB_API/repos/$repo/tags?per_page=100"); then
    log "  ERROR: could not fetch tags"
    R_FAIL+=("$name"); FAILED=1; return 0
  fi
  tag=$(jq -r '.[].name' <<<"$tags" | grep -E '^v?[0-9]+(\.[0-9]+)*$' | sort -V | tail -n1)
  if [[ -z $tag ]]; then
    log "  ERROR: no semver tags found"
    R_FAIL+=("$name"); FAILED=1; return 0
  fi
  local ver
  ver=$(strip_version "$tag" "$name")
  log "  latest tag: $tag (version $ver)"

  local desc license
  desc=$(clean_desc "$(desc_for "$repo")")
  [[ -n $desc ]] || desc="$name"
  license=${license_ov:-$(license_for "$repo")}
  [[ -n $license ]] || license="unknown"

  write_go_pkgbuild "$name" "$repo" "$ver" "$tag" "$desc" "$license" "$depends_csv"
  log "  builds/${name}_PKGBUILD updated (pkgver=$ver)"
  R_OK+=("$name -> $ver")
}

process_npm() { # $1=name $2=repo $3=npm_pkg $4=scripts_csv $5=depends_csv $6=license_ov
  local name=$1 repo=$2 npm_pkg=$3 scripts_csv=$4 depends_csv=$5 license_ov=$6
  local builddir="$PKGBUILD_DIR/.build-$name"
  [[ -n $npm_pkg ]] || npm_pkg=$name

  local enc=${npm_pkg//\//%2F}
  local meta ver tarball
  if ! meta=$(curl --compressed -fsSL "$NPM_REGISTRY/$enc"); then
    log "  ERROR: could not fetch npm metadata for $npm_pkg"
    R_FAIL+=("$name"); FAILED=1; return 0
  fi
  ver=$(jq -r '."dist-tags".latest // empty' <<<"$meta")
  if [[ -z $ver ]]; then
    log "  ERROR: no latest version for $npm_pkg"
    R_FAIL+=("$name"); FAILED=1; return 0
  fi
  tarball=$(jq -r --arg v "$ver" '.versions[$v].dist.tarball // empty' <<<"$meta")
  if [[ -z $tarball ]]; then
    log "  ERROR: no tarball for $npm_pkg@$ver"
    R_FAIL+=("$name"); FAILED=1; return 0
  fi
  log "  latest: $npm_pkg@$ver"

  # The npm registry exposes sha1/sha512, not sha256; download to compute it.
  local sha
  mkdir -p "$builddir"
  if ! curl --compressed -fsSL -o "$builddir/$name-$ver.tgz" "$tarball"; then
    log "  ERROR: download failed"
    rm -rf "$builddir"
    R_FAIL+=("$name"); FAILED=1; return 0
  fi
  sha=$(sha256sum "$builddir/$name-$ver.tgz" | awk '{print $1}')
  rm -rf "$builddir"

  local desc license
  desc=$(clean_desc "$(desc_for "$repo")")
  [[ -n $desc ]] || desc=$(clean_desc "$(jq -r '.description // empty' <<<"$meta")")
  [[ -n $desc ]] || desc="$name"
  license=${license_ov:-$(jq -r '.license // empty' <<<"$meta")}
  [[ -n $license ]] || license="unknown"

  write_npm_pkgbuild "$name" "$repo" "$ver" "$tarball" "$sha" "$desc" "$license" "$scripts_csv" "$depends_csv"
  log "  builds/${name}_PKGBUILD updated (pkgver=$ver)"
  R_OK+=("$name -> $ver")
}

process_app() { # $1=name $2=repo $3=extra
  local name=$1 repo=$2 extra=${3:-}

  log ""
  log "=== $name ($repo) ==="

  local type=release asset_ov="" depends_csv="" npm_pkg="" scripts_csv="" license_ov=""
  if [[ -n $extra ]]; then
    local pair pairs=()
    IFS=';' read -ra pairs <<<"$extra"
    for pair in "${pairs[@]}"; do
      [[ -z $pair ]] && continue
      case ${pair%%=*} in
      type) type=${pair#*=} ;;
      asset) asset_ov=${pair#*=} ;;
      depends) depends_csv=${pair#*=} ;;
      npm) npm_pkg=${pair#*=} ;;
      scripts) scripts_csv=${pair#*=} ;;
      license) license_ov=${pair#*=} ;;
      *) log "  warning: unknown override '$pair'" ;;
      esac
    done
  fi

  case $type in
  release) process_release "$name" "$repo" "$asset_ov" "$depends_csv" ;;
  go) process_go "$name" "$repo" "$depends_csv" "$license_ov" ;;
  npm) process_npm "$name" "$repo" "$npm_pkg" "$scripts_csv" "$depends_csv" "$license_ov" ;;
  *)
    log "  ERROR: unknown type '$type'"
    R_FAIL+=("$name"); FAILED=1
    ;;
  esac
}

# --------------------------------------------------------------------- main ---

while IFS=$' \t' read -r name repo extra _ || [[ -n ${name:-} ]]; do
  [[ -z ${name:-} || $name == \#* ]] && continue
  if [[ -z ${repo:-} ]]; then
    log "malformed line in gitlist.txt: $name"
    continue
  fi
  if ((${#SELECTED[@]})); then
    skip=1
    for s in "${SELECTED[@]}"; do
      [[ $s == "$name" ]] && skip=0
    done
    ((skip)) && continue
  fi
  process_app "$name" "$repo" "${extra:-}"
done <"$APPS_CONF"

log ""
log "================ summary ================"
for r in "${R_OK[@]:-}"; do [[ -n $r ]] && log "  ok      $r"; done
for r in "${R_SKIP[@]:-}"; do [[ -n $r ]] && log "  skipped $r"; done
for r in "${R_FAIL[@]:-}"; do [[ -n $r ]] && log "  FAILED  $r"; done
log "========================================="

exit $FAILED
